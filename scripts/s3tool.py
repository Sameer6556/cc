"""Host-side helper for the SeaweedFS object store (buckets, dataset, model artefacts).

Credentials are read from .secrets/s3.env (generated by scripts/secrets.sh, git-ignored) and the
endpoint defaults to the k3d NodePort http://127.0.0.1:30333.

  python scripts/s3tool.py buckets                          create the buckets datasets and models
  python scripts/s3tool.py seed-data                        upload commands_pool.jsonl and the validation texts
  python scripts/s3tool.py put-model v1 artifacts/models/v1 write model.sha256, upload to s3://models/v1/
  python scripts/s3tool.py release-model v1                 download the GitHub Release model-v1, verify, upload
  python scripts/s3tool.py get s3://datasets/v1/ datasets/v1     download every object under a prefix
  python scripts/s3tool.py put FILE s3://bucket/key         upload one file
  python scripts/s3tool.py ls                               list every object in both buckets
"""
import argparse
import hashlib
import json
import os
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUCKETS = ('datasets', 'models')
DEFAULT_REPO = os.environ.get('GITHUB_REPOSITORY', 'Sameer6556/cc')


def load_env():
    path = os.path.join(ROOT, '.secrets', 's3.env')
    env = {}
    if os.path.exists(path):
        for line in open(path, encoding='utf-8'):
            if '=' in line:
                k, v = line.strip().split('=', 1)
                env[k] = v
    return env


def client():
    import boto3
    from botocore.config import Config

    env = load_env()  # the credentials generated for this cluster win over anything in the environment
    return boto3.client(
        's3',
        endpoint_url=os.environ.get('S3_HOST_ENDPOINT', 'http://127.0.0.1:30333'),
        aws_access_key_id=env.get('S3_ADMIN_ACCESS_KEY') or os.environ.get('AWS_ACCESS_KEY_ID'),
        aws_secret_access_key=env.get('S3_ADMIN_SECRET_KEY') or os.environ.get('AWS_SECRET_ACCESS_KEY'),
        region_name='us-east-1',
        config=Config(s3={'addressing_style': 'path'}, signature_version='s3v4',
                      retries={'max_attempts': 8, 'mode': 'standard'}),
    )


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for block in iter(lambda: f.read(1 << 20), b''):
            h.update(block)
    return h.hexdigest()


def write_checksums(model_dir):
    """model.sha256 in `sha256sum` format, one line per model/tokenizer file, sorted by name."""
    names = sorted(n for n in os.listdir(model_dir)
                   if os.path.isfile(os.path.join(model_dir, n)) and n != 'model.sha256')
    lines = [f'{sha256_file(os.path.join(model_dir, n))}  {n}\n' for n in names]
    with open(os.path.join(model_dir, 'model.sha256'), 'w', encoding='utf-8') as f:
        f.writelines(lines)
    return names


def verify_checksums(model_dir):
    bad = []
    for line in open(os.path.join(model_dir, 'model.sha256'), encoding='utf-8'):
        digest, name = line.split(maxsplit=1)
        name = name.strip()
        if sha256_file(os.path.join(model_dir, name)) != digest:
            bad.append(name)
    if bad:
        sys.exit(f'checksum mismatch: {bad}')


def cmd_buckets(_a):
    c = client()
    existing = {b['Name'] for b in c.list_buckets().get('Buckets', [])}
    for b in BUCKETS:
        if b not in existing:
            c.create_bucket(Bucket=b)
            print(f'created bucket {b}')
        else:
            print(f'bucket {b} exists')


def cmd_seed_data(_a):
    c = client()
    c.upload_file(os.path.join(ROOT, 'data', 'commands_pool.jsonl'), 'datasets', 'commands_pool.jsonl')
    print('uploaded data/commands_pool.jsonl -> s3://datasets/commands_pool.jsonl')
    # Only ids and texts: the gold labels never enter the pipeline.
    texts = ''.join(json.dumps({'id': r['id'], 'text': r['text']}) + '\n'
                    for r in map(json.loads, open(os.path.join(ROOT, 'data', 'validation.jsonl'), encoding='utf-8')))
    c.put_object(Bucket='datasets', Key='eval/validation_texts.jsonl', Body=texts.encode('utf-8'))
    print('uploaded validation texts (no labels) -> s3://datasets/eval/validation_texts.jsonl')


def upload_dir(c, local_dir, bucket, prefix):
    for n in sorted(os.listdir(local_dir)):
        p = os.path.join(local_dir, n)
        if os.path.isfile(p):
            c.upload_file(p, bucket, f'{prefix}/{n}')
            print(f'  s3://{bucket}/{prefix}/{n}  ({os.path.getsize(p)} bytes)')


def cmd_put_model(a):
    names = write_checksums(a.dir)
    print(f'model.sha256 covers {len(names)} files: {names}')
    upload_dir(client(), a.dir, 'models', a.version)
    os.makedirs(os.path.join(ROOT, 'models', a.version), exist_ok=True)
    with open(os.path.join(a.dir, 'model.sha256'), encoding='utf-8') as src, \
            open(os.path.join(ROOT, 'models', a.version, 'model.sha256'), 'w', encoding='utf-8') as dst:
        dst.write(src.read())
    print(f'copied checksums to models/{a.version}/model.sha256')


def cmd_release_model(a):
    base = f'https://github.com/{a.repo}/releases/download/model-{a.version}'
    dest = os.path.join(ROOT, 'artifacts', 'release', a.version)
    os.makedirs(dest, exist_ok=True)

    def fetch(name):
        print(f'downloading {base}/{name}', flush=True)
        urllib.request.urlretrieve(f'{base}/{name}', os.path.join(dest, name))

    fetch('model.sha256')
    for line in open(os.path.join(dest, 'model.sha256'), encoding='utf-8'):
        fetch(line.split(maxsplit=1)[1].strip())
    verify_checksums(dest)
    print('all release assets match model.sha256')
    upload_dir(client(), dest, 'models', a.version)


def cmd_get(a):
    c = client()
    bucket, _, prefix = a.uri[5:].partition('/')
    os.makedirs(a.dest, exist_ok=True)
    for page in c.get_paginator('list_objects_v2').paginate(Bucket=bucket, Prefix=prefix):
        for o in page.get('Contents', []):
            name = o['Key'][len(prefix):].lstrip('/')
            if name and '/' not in name:
                c.download_file(bucket, o['Key'], os.path.join(a.dest, name))
                print(f'{a.uri.rstrip("/")}/{name} -> {os.path.join(a.dest, name)}')


def cmd_put(a):
    bucket, _, key = a.uri[5:].partition('/')
    client().upload_file(a.path, bucket, key)
    print(f'{a.path} -> {a.uri}')


def cmd_ls(_a):
    c = client()
    for b in c.list_buckets().get('Buckets', []):
        print(f'bucket {b["Name"]}')
        for page in c.get_paginator('list_objects_v2').paginate(Bucket=b['Name']):
            for o in page.get('Contents', []):
                print(f'  {o["LastModified"]:%Y-%m-%d %H:%M:%S}  {o["Size"]:>12}  s3://{b["Name"]}/{o["Key"]}')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest='cmd', required=True)
    sub.add_parser('buckets').set_defaults(fn=cmd_buckets)
    sub.add_parser('seed-data').set_defaults(fn=cmd_seed_data)
    p = sub.add_parser('put-model')
    p.add_argument('version')
    p.add_argument('dir')
    p.set_defaults(fn=cmd_put_model)
    p = sub.add_parser('release-model')
    p.add_argument('version')
    p.add_argument('--repo', default=DEFAULT_REPO)
    p.set_defaults(fn=cmd_release_model)
    p = sub.add_parser('get')
    p.add_argument('uri')
    p.add_argument('dest')
    p.set_defaults(fn=cmd_get)
    p = sub.add_parser('put')
    p.add_argument('path')
    p.add_argument('uri')
    p.set_defaults(fn=cmd_put)
    sub.add_parser('ls').set_defaults(fn=cmd_ls)
    a = ap.parse_args()
    a.fn(a)


if __name__ == '__main__':
    main()
